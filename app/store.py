    def settings(self) -> Dict[str, Any]:
        return self.data["settings"]

    @property
    def collections(self) -> List[Dict[str, Any]]:
        return self.data["collections"]

    @property
    def history(self) -> List[Dict[str, Any]]:
        return self.data["history"]

